import argparse
import json
from collections import Counter, defaultdict
from pathlib import Path
from typing import Any


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Merge Yiwan safe batch JSON files into one research pack.")
    parser.add_argument("files", nargs="+", help="Batch JSON files generated by YiwanSafeBatchCollector.")
    parser.add_argument("--output", required=True, help="Output merged research pack JSON path.")
    parser.add_argument("--summary", help="Output merge summary JSON path.")
    return parser.parse_args()


def read_json(path: Path) -> Any:
    return json.loads(path.read_text(encoding="utf-8"))


def write_json(path: Path, data: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, ensure_ascii=False, indent=2), encoding="utf-8")


def as_rows(value: Any) -> list[dict[str, Any]]:
    if isinstance(value, list):
        return [row for row in value if isinstance(row, dict)]
    if isinstance(value, dict):
        for key in ("list", "rows", "data", "items"):
            if isinstance(value.get(key), list):
                return [row for row in value[key] if isinstance(row, dict)]
    return []


def row_key(row: dict[str, Any]) -> tuple[str, str, str]:
    code = str(row.get("stock_code") or row.get("code") or row.get("dm") or "").zfill(6)
    date = str(row.get("stock_date") or row.get("date_time") or row.get("date") or row.get("source_date") or "")
    page = str(row.get("source_page") or "")
    return code, date, page


def merge(files: list[Path]) -> tuple[dict[str, Any], dict[str, Any]]:
    indicators: list[dict[str, Any]] = []
    dark_factor_by_date: dict[str, list[dict[str, Any]]] = defaultdict(list)
    main_force_by_date: dict[str, list[dict[str, Any]]] = defaultdict(list)
    active_ap_stock_by_date: dict[str, list[dict[str, Any]]] = defaultdict(list)
    big_ap_by_date: dict[str, Any] = {}
    big_market_daily_by_date: dict[str, Any] = {}
    file_reports = []
    run_ids = set()
    sources = set()

    for path in files:
        payload = read_json(path)
        meta = payload.get("meta", {}) if isinstance(payload, dict) else {}
        batch_type = meta.get("type", "unknown")
        run_ids.add(meta.get("runId"))
        sources.add(meta.get("source"))

        if batch_type == "indicators_pages":
            rows = as_rows(payload.get("indicators_current"))
            indicators.extend(rows)
            file_reports.append({
                "file": str(path),
                "type": batch_type,
                "startPage": meta.get("startPage"),
                "endPage": meta.get("endPage"),
                "rows": len(rows),
            })
            continue

        if batch_type == "date_batch":
            row_count = 0
            for date, rows_value in (payload.get("dark_factor_by_date") or {}).items():
                rows = as_rows(rows_value)
                dark_factor_by_date[date].extend(rows)
                row_count += len(rows)
            for date, rows_value in (payload.get("main_force_by_date") or {}).items():
                rows = as_rows(rows_value)
                main_force_by_date[date].extend(rows)
                row_count += len(rows)
            for date, rows_value in (payload.get("active_ap_stock_by_date") or {}).items():
                rows = as_rows(rows_value)
                active_ap_stock_by_date[date].extend(rows)
                row_count += len(rows)
            big_ap_by_date.update(payload.get("big_ap_by_date") or {})
            big_market_daily_by_date.update(payload.get("big_market_daily_by_date") or {})
            file_reports.append({
                "file": str(path),
                "type": batch_type,
                "dates": meta.get("dates", []),
                "rows": row_count,
            })
            continue

        file_reports.append({
            "file": str(path),
            "type": batch_type,
            "rows": 0,
            "warning": "unsupported batch type",
        })

    key_counts = Counter(row_key(row) for row in indicators)
    duplicate_indicator_keys = [key for key, count in key_counts.items() if count > 1 and any(key)]
    deduped_indicators = []
    seen = set()
    for row in indicators:
        key = row_key(row)
        if key in seen:
            continue
        seen.add(key)
        deduped_indicators.append(row)

    run_ids.discard(None)
    sources.discard(None)
    pack = {
        "meta": {
            "type": "merged_safe_batches",
            "source": sorted(sources)[0] if sources else "",
            "runIds": sorted(run_ids),
            "fileCount": len(files),
            "note": "由 YiwanSafeBatchCollector 分批文件合并。仅保存真实采集明细，不补数据。",
        },
        "indicators_current": deduped_indicators,
        "dark_factor_by_date": dict(dark_factor_by_date),
        "main_force_by_date": dict(main_force_by_date),
        "active_ap_stock_by_date": dict(active_ap_stock_by_date),
        "big_market_current": None,
        "big_ap_by_date": big_ap_by_date,
        "big_market_daily_by_date": big_market_daily_by_date,
        "sector_by_code": {},
    }

    pages = sorted({
        int(row.get("source_page"))
        for row in deduped_indicators
        if str(row.get("source_page") or "").isdigit()
    })
    dates = sorted({
        str(row.get("stock_date") or row.get("date_time") or "")
        for row in deduped_indicators
        if row.get("stock_date") or row.get("date_time")
    })
    summary = {
        "input_files": file_reports,
        "file_count": len(files),
        "indicator_rows_raw": len(indicators),
        "indicator_rows": len(deduped_indicators),
        "duplicate_indicator_keys": len(duplicate_indicator_keys),
        "indicator_pages": pages,
        "indicator_date_values": dates,
        "dark_factor_dates": sorted(dark_factor_by_date),
        "main_force_dates": sorted(main_force_by_date),
        "active_ap_stock_dates": sorted(active_ap_stock_by_date),
    }
    return pack, summary


def main() -> None:
    args = parse_args()
    files = [Path(file).expanduser() for file in args.files]
    pack, summary = merge(files)
    output = Path(args.output).expanduser()
    summary_path = Path(args.summary).expanduser() if args.summary else output.with_name(f"{output.stem}-summary.json")
    write_json(output, pack)
    write_json(summary_path, summary)
    print(json.dumps({
        "output": str(output),
        "summary": str(summary_path),
        "indicator_rows": summary["indicator_rows"],
        "indicator_rows_raw": summary["indicator_rows_raw"],
        "duplicate_indicator_keys": summary["duplicate_indicator_keys"],
        "file_count": summary["file_count"],
        "indicator_pages": summary["indicator_pages"],
    }, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
